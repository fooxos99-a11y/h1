import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true });
try {
  for (const width of [360, 768, 1440]) {
    const context = await browser.newContext({ viewport: { width, height: 900 }, serviceWorkers: 'block' });
    await context.addInitScript(() => { globalThis.localStorage.setItem('wajeh_role', 'supervisor'); globalThis.localStorage.setItem('wajeh_supervisor_id', '990'); });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('http://127.0.0.1:3011/tests/fixtures/local-recitation.html', { waitUntil: 'domcontentloaded' });
    await page.getByRole('button', { name: 'حفظ', exact: true }).waitFor();
    const openedAt = Date.now();
    await page.getByRole('button', { name: 'حفظ', exact: true }).click();
    await page.getByRole('dialog').waitFor();
    assert.ok(Date.now() - openedAt < 1000, 'unchanged memorization must open immediately');
    assert.equal(await page.evaluate(() => globalThis.localRecitationFixture.rangeCalls.length), 0);
    assert.equal(await page.evaluate(() => globalThis.localRecitationFixture.ayahCalls), 0);
    assert.equal(await page.getByRole('spinbutton', { name: 'عدد الأخطاء' }).count(), 1);
    assert.equal(await page.getByText('المقطع 1', { exact: true }).count(), 0);
    await page.getByRole('dialog').evaluate(async node => { await Promise.all(node.getAnimations().map(animation => animation.finished)); });
    assert.ok(await page.getByRole('dialog').evaluate(node => {
      const box = node.getBoundingClientRect();
      return box.left >= 0 && box.right <= globalThis.innerWidth && box.top >= 0 && box.bottom <= globalThis.innerHeight;
    }), 'the daily dialog must stay inside the viewport');
    await page.screenshot({ path: `outputs/local-recitation-followup/daily-${width}.png` });
    await page.getByRole('button', { name: 'إغلاق', exact: true }).click();
    const compensation = page.getByRole('button', { name: 'التعويض', exact: true });
    const identity = page.locator('.recitation-person');
    assert.equal(await identity.getByRole('button', { name: 'التعويض', exact: true }).count(), 1);
    assert.ok(await compensation.evaluate(node => node.getBoundingClientRect().height >= 44));
    await compensation.click();
    const compensationDialog = page.getByRole('dialog');
    assert.equal(await compensationDialog.getByRole('button', { name: /حفظ/ }).count(), 1);
    assert.equal(await compensationDialog.getByRole('button', { name: /مراجعة/ }).count(), 1);
    assert.equal(await compensationDialog.getByRole('button', { name: /ربط/ }).count(), 0);
    await compensationDialog.evaluate(async node => { await Promise.all(node.getAnimations().map(animation => animation.finished)); });
    assert.ok(await compensationDialog.evaluate(node => {
      const box = node.getBoundingClientRect();
      return box.left >= 0 && box.right <= globalThis.innerWidth && box.top >= 0 && box.bottom <= globalThis.innerHeight;
    }), 'the compensation dialog must stay inside the viewport');
    await page.screenshot({ path: `outputs/local-recitation-followup/compensation-${width}.png` });
    await compensationDialog.getByRole('button', { name: /حفظ/ }).click();
    await page.getByRole('spinbutton', { name: 'عدد الأخطاء' }).waitFor();
    assert.equal(await page.getByRole('spinbutton', { name: 'عدد الأخطاء' }).count(), 1);
    await page.getByRole('button', { name: 'زيادة عدد الأخطاء' }).click();
    await page.getByRole('button', { name: 'إنهاء', exact: true }).click();
    await page.waitForFunction(() => globalThis.localRecitationFixture.commits.length === 1);
    const savedCompensation = await page.evaluate(() => globalThis.localRecitationFixture.commits[0]);
    assert.deepEqual(savedCompensation.tasks.map(item => item.taskId).sort((a, b) => a - b), [10, 11]);
    assert.ok(savedCompensation.tasks.every(item => item.payload.compensation === true));
    assert.equal(savedCompensation.tasks.reduce((sum, item) => sum + item.payload.mistakeCount, 0), 1);
    await page.getByRole('button', { name: 'حفظ', exact: true }).waitFor();
    await compensation.click();
    assert.equal(await page.getByRole('dialog').getByRole('button', { name: /حفظ/ }).count(), 0);
    await page.getByRole('dialog').getByRole('button', { name: /مراجعة/ }).click();
    await page.getByRole('spinbutton', { name: 'عدد الأخطاء' }).waitFor();
    await page.getByRole('button', { name: 'إنهاء', exact: true }).click();
    await page.waitForFunction(() => globalThis.localRecitationFixture.commits.length === 2);
    const savedReview = await page.evaluate(() => globalThis.localRecitationFixture.commits[1]);
    assert.deepEqual(savedReview.tasks.map(item => item.taskId), [12]);
    assert.ok(savedReview.tasks.every(item => item.payload.compensation === true));
    assert.equal(await compensation.count(), 0);
    await page.getByRole('button', { name: 'حفظ', exact: true }).click();
    await page.getByRole('button', { name: 'إنهاء', exact: true }).click();
    await page.waitForFunction(() => globalThis.localRecitationFixture.commits.length === 3);
    const savedDaily = await page.evaluate(() => globalThis.localRecitationFixture.commits[2]);
    assert.deepEqual(savedDaily.tasks.map(item => item.taskId).sort((a, b) => a - b), [1, 6, 7]);
    assert.ok(savedDaily.tasks.every(item => item.payload.compensation === false));
    await page.getByRole('button', { name: 'ربط', exact: true }).click();
    assert.equal(await page.getByRole('spinbutton', { name: 'عدد الأخطاء' }).count(), 1);
    assert.equal(await page.getByText('المقطع 1', { exact: true }).count(), 0);
    await page.getByRole('button', { name: 'زيادة عدد الأخطاء' }).click();
    await page.getByRole('button', { name: 'إنهاء', exact: true }).click();
    await page.waitForFunction(() => globalThis.localRecitationFixture.commits.length === 4);
    assert.equal(await page.evaluate(() => globalThis.localRecitationFixture.commits[3].tasks.reduce((sum, item) => sum + item.payload.mistakeCount, 0)), 1);
    await page.reload({ waitUntil: 'domcontentloaded' });
    await page.getByRole('button', { name: 'إظهار جميع المقادير' }).click();
    const saved = page.locator('[data-recitation-slot="saved"]');
    await saved.getByRole('combobox', { name: 'آية النهاية' }).click();
    await page.getByRole('option', { name: '6', exact: true }).click();
    assert.equal(await page.getByRole('dialog').count(), 0);
    await page.getByRole('button', { name: 'حفظ', exact: true }).click();
    await page.getByRole('dialog').waitFor();
    await page.waitForFunction(() => globalThis.localRecitationFixture.rangeCalls.length === 1);
    await page.evaluate(() => globalThis.localRecitationFixture.releaseRange());
    await page.getByRole('spinbutton', { name: 'عدد الأخطاء' }).waitFor();
    assert.equal(await page.evaluate(() => globalThis.localRecitationFixture.evaluationCalls), 1, 'range preparation must not reload the entire teacher session');
    await page.getByRole('button', { name: 'إغلاق', exact: true }).click();
    const review = page.locator('[data-recitation-slot="review"]');
    await review.getByRole('combobox', { name: 'سورة النهاية' }).click();
    await page.getByRole('option', { name: 'الفلق', exact: true }).click();
    await review.getByRole('combobox', { name: 'آية النهاية' }).click();
    await page.keyboard.press('ArrowDown'); await page.keyboard.press('Enter');
    assert.ok(await review.getByRole('combobox', { name: 'آية النهاية' }).evaluate(node => node === globalThis.document.activeElement));
    assert.ok(await page.evaluate(() => globalThis.document.documentElement.scrollWidth <= globalThis.innerWidth));
    const sizes = await review.getByRole('combobox').evaluateAll(nodes => nodes.map(node => ({ width: node.getBoundingClientRect().width, height: node.getBoundingClientRect().height })));
    assert.ok(sizes.every(size => size.width >= 44 && size.height >= 44));
    await page.screenshot({ path: `outputs/local-recitation-followup/recitation-${width}.png` });
    assert.deepEqual(errors, []);
    globalThis.console.log(JSON.stringify({ width, immediateCountOpening: true, oneDailyCounter: true, separateCompensation: true, oneLinkCounter: true, directEndSelectors: true, noFullRefresh: true, overflow: false }));
    await context.close();
  }
} finally { await browser.close(); }
